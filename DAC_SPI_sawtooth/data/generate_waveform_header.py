"""Generate waveform_data.h directly, without timestamps or a text file."""

import argparse
from pathlib import Path


# Waveform settings: playback speed is controlled by the C firmware.
NUM_POINTS = 10000
FALL_FRACTION = 0.1  # 90% rising, 10% falling
DAC_MAX_VALUE = 4095  # 12-bit DAC
DAC_FULL_SCALE_VOLTAGE = 5.0  # Must match the hardware reference/gain
V_MIN = 0.7
V_MAX = 4.3


def generate_values():
    if NUM_POINTS < 2:
        raise ValueError("NUM_POINTS must be at least 2")
    if not 0 < FALL_FRACTION < 1:
        raise ValueError("FALL_FRACTION must be between 0 and 1")
    if not 0 <= V_MIN < V_MAX <= DAC_FULL_SCALE_VOLTAGE:
        raise ValueError("Voltage range must fit within the DAC full scale")
    if not 0 < DAC_MAX_VALUE <= 4095:
        raise ValueError("DAC_MAX_VALUE must fit the 12-bit DAC")

    fall_points = round(NUM_POINTS * FALL_FRACTION)
    rise_points = NUM_POINTS - fall_points
    if rise_points < 1 or fall_points < 1:
        raise ValueError("Both waveform sections need at least one point")

    dac_min = int(V_MIN / DAC_FULL_SCALE_VOLTAGE * DAC_MAX_VALUE)
    dac_max = int(V_MAX / DAC_FULL_SCALE_VOLTAGE * DAC_MAX_VALUE)
    span = dac_max - dac_min

    # The fall begins at the peak. Its final endpoint is supplied by the
    # first sample of the next cycle, avoiding duplicate endpoints.
    values = [int(dac_min + span * i / rise_points)
              for i in range(rise_points)]
    values.extend(int(dac_max - span * i / fall_points)
                  for i in range(fall_points))
    return values, rise_points, fall_points


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).resolve().with_name("waveform_data.h"),
        help="Header path (default: waveform_data.h beside this script)",
    )
    args = parser.parse_args()
    values, rise_points, fall_points = generate_values()

    with args.output.open("w") as header:
        header.write("// Generated by generate_waveform_header.py\n")
        header.write(f"// {rise_points} rising samples, {fall_points} falling samples.\n")
        header.write("// Sample timing is controlled by the C firmware.\n")
        header.write("#ifndef WAVEFORM_DATA_H\n#define WAVEFORM_DATA_H\n\n")
        header.write("#include <stdint.h>\n\n")
        header.write(f"#define WAVEFORM_SIZE {len(values)}\n\n")
        header.write("static const uint16_t sawtooth_wave[WAVEFORM_SIZE] = {\n")
        for start in range(0, len(values), 10):
            header.write("    " + ", ".join(map(str, values[start:start + 10])) + ",\n")
        header.write("};\n\n#endif // WAVEFORM_DATA_H\n")

    print(f"Generated {args.output} with {len(values)} samples")
    print(f"Rise: {rise_points}; fall: {fall_points}; DAC range: {min(values)}–{max(values)}")


if __name__ == "__main__":
    main()
